package com.fungle.brume.scan;

import com.fungle.brume.config.model.AnonymizerConfig;
import com.fungle.brume.config.model.Strategy;
import com.fungle.brume.schema.model.ColumnMetadata;
import com.fungle.brume.schema.model.DatabaseSchema;
import com.fungle.brume.schema.model.TableMetadata;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.yaml.snakeyaml.Yaml;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Unit tests for {@link ScanYamlWriter} — asserts both the human-readable output
 * (provenance comments, section ordering) and that the generated document is valid
 * YAML that SnakeYAML can parse. Does <em>not</em> round-trip through the Jackson-based
 * {@link AnonymizerConfig} loader : the scan output deliberately includes a stubbed
 * {@code extraction.tables} list that fails ConfigValidator (which requires at least
 * one table) — that is intentional, the user fills it in.
 */
class ScanYamlWriterTest {

    @Test
    void rendersValidYamlWithProvenanceComments() {
        DatabaseSchema schema = singleTable("users", List.of(
                new ColumnMetadata("id", "bigint", false),
                new ColumnMetadata("email", "varchar", true)
        ), "id");

        String yaml = ScanYamlWriter.render(ScanConfigBuilder.build(schema));

        assertThat(yaml)
                .contains("# brume.yml — generated by `brume scan`")
                .contains("- name: id")
                .contains("# detected via primary key (numeric)")
                .contains("strategy: FPE_ID")
                .contains("- name: email")
                .contains("# detected via email")
                .contains("strategy: FAKE")
                .contains("type: EMAIL");

        // Parses as valid YAML
        Object parsed = new Yaml().load(yaml);
        assertThat(parsed).isInstanceOf(Map.class);
        @SuppressWarnings("unchecked")
        Map<String, Object> doc = (Map<String, Object>) parsed;
        assertThat(doc).containsKeys("extraction", "anonymization");
    }

    @Test
    void emptyResultEmitsTodoStubAndStillValidYaml() {
        DatabaseSchema schema = new DatabaseSchema(new LinkedHashMap<>());

        String yaml = ScanYamlWriter.render(ScanConfigBuilder.build(schema));

        assertThat(yaml)
                .contains("# TODO: declare at least one table to extract")
                .contains("# No columns matched a known PII / PK pattern");

        // Still parses — the TODO lines are comments.
        Object parsed = new Yaml().load(yaml);
        assertThat(parsed).isInstanceOf(Map.class);
    }

    @Test
    void omitsTypeLineWhenSuggestionHasNoSemanticType() {
        // password_hash -> HASH with no semantic type.
        DatabaseSchema schema = singleTable("accounts", List.of(
                new ColumnMetadata("password_hash", "varchar", false)
        ), null);

        String yaml = ScanYamlWriter.render(ScanConfigBuilder.build(schema));

        assertThat(yaml)
                .contains("strategy: " + Strategy.HASH.name())
                .doesNotContain("          type:");
    }

    @Test
    @DisplayName("#26c — any legal PostgreSQL name reads back exactly from the generated YAML")
    void namesSurviveTheYamlRoundTrip() {
        List<String> names = List.of("users", "prénom", "Account", "nom de famille", "zip code",
                "a: b", "#tag", "- dash", "it's", "say \"hi\"", "back\\slash", "null", "On", "yes",
                "123", "line\nbreak", "tab\there", "😀");

        assertThat(ScanYamlWriter.yamlScalar("prénom")).isEqualTo("prénom");
        assertThat(ScanYamlWriter.yamlScalar("nom de famille")).isEqualTo("\"nom de famille\"");
        for (String name : names) {
            @SuppressWarnings("unchecked")
            Map<String, Object> doc = (Map<String, Object>) new Yaml().load("name: " + ScanYamlWriter.yamlScalar(name) + "\n");
            assertThat(doc.get("name")).as(name).isEqualTo(name);
        }
    }

    private static DatabaseSchema singleTable(String name, List<ColumnMetadata> columns, String pk) {
        Map<String, TableMetadata> tables = new LinkedHashMap<>();
        tables.put(name, new TableMetadata(name, columns, List.of(), pk));
        return new DatabaseSchema(tables);
    }
}
