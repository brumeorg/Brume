package com.fungle.brume.scan;

import com.fungle.brume.scan.ColumnStrategyMapper.Suggestion;
import com.fungle.brume.scan.ScanConfigBuilder.ScanResult;
import com.fungle.brume.scan.ScanConfigBuilder.SuggestedColumn;
import com.fungle.brume.scan.ScanConfigBuilder.SuggestedTable;

/**
 * Renders a {@link ScanResult} as a {@code brume.yml} string, with inline provenance
 * comments ({@code # detected via pattern 'xxx'}) next to each generated rule.
 *
 * <p>Hand-rolled rather than driven by SnakeYAML : the writer is 90 % layout concerns
 * (comments, blank lines, section headers) that SnakeYAML's representer can only emit
 * through callbacks and overridden event classes — more code for less clarity. The
 * output is still valid YAML (two-space indent, strings are plain scalars, no reserved
 * characters emitted).
 *
 * <p>The {@code extraction} block is intentionally emitted as a TODO stub : extraction
 * is a business choice (which tables, which filters) that the schema alone cannot infer.
 * The operator fills it in before running {@code brume plan}.
 */
public final class ScanYamlWriter {

    private ScanYamlWriter() {
    }

    /**
     * Renders a complete {@code brume.yml} document for the given scan result.
     *
     * @param result the scan output
     * @return the YAML document as a single string, newline-terminated
     */
    public static String render(ScanResult result) {
        StringBuilder sb = new StringBuilder(2_048);

        sb.append("# brume.yml — generated by `brume scan`\n");
        sb.append("# ").append(result.totalSuggestions())
                .append(" rule(s) auto-detected across ").append(result.tables().size())
                .append(" table(s). Review each rule, then run `brume plan` to preview the extraction.\n");
        sb.append("#\n");
        sb.append("# Columns not listed below had no pattern match — add rules by hand if needed.\n");
        sb.append("# Foreign-key columns are intentionally omitted : FkStrategyPropagator copies\n");
        sb.append("# the parent primary key's strategy onto them at run time.\n\n");

        writeExtractionStub(sb, result);
        sb.append('\n');
        writeAnonymization(sb, result);

        return sb.toString();
    }

    private static void writeExtractionStub(StringBuilder sb, ScanResult result) {
        sb.append("extraction:\n");
        sb.append("  fk_depth: 3\n");
        sb.append("  fetch_size: 1000\n");
        sb.append("  batch_size: 500\n");
        sb.append("  chunk_size: 10000\n");
        sb.append("  tables:\n");
        if (result.tables().isEmpty()) {
            sb.append("    # TODO: declare at least one table to extract, e.g.\n");
            sb.append("    # - table: your_table\n");
            sb.append("    #   filter: \"created_at >= '2025-01-01'\"\n");
            return;
        }
        sb.append("    # TODO: review this list and add filters where appropriate.\n");
        for (SuggestedTable table : result.tables()) {
            sb.append("    - table: ").append(table.tableName()).append('\n');
            sb.append("      filter:\n");
        }
    }

    private static void writeAnonymization(StringBuilder sb, ScanResult result) {
        sb.append("anonymization:\n");
        sb.append("  tables:\n");
        if (result.tables().isEmpty()) {
            sb.append("    # No columns matched a known PII / PK pattern on this schema.\n");
            sb.append("    # Add rules by hand or extend ColumnStrategyMapper's pattern list.\n");
            return;
        }
        for (int i = 0; i < result.tables().size(); i++) {
            if (i > 0) sb.append('\n');
            writeTable(sb, result.tables().get(i));
        }
    }

    private static void writeTable(StringBuilder sb, SuggestedTable table) {
        sb.append("    - table: ").append(table.tableName()).append('\n');
        sb.append("      columns:\n");
        for (SuggestedColumn col : table.columns()) {
            writeColumn(sb, col);
        }
    }

    private static void writeColumn(StringBuilder sb, SuggestedColumn col) {
        Suggestion s = col.suggestion();
        sb.append("        - name: ").append(col.columnName())
                .append("        # detected via ").append(s.matchedPattern()).append('\n');
        sb.append("          strategy: ").append(s.strategy().name()).append('\n');
        if (s.semanticType() != null) {
            sb.append("          type: ").append(s.semanticType().name()).append('\n');
        }
    }
}
